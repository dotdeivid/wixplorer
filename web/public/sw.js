// WiXplorer Service Worker
// Caches hashed static assets (JS/CSS) for instant load on repeat visits.
// API calls (/api/*) are never cached — always go to network.

const CACHE = 'pt-v1';

// Ruta base de la app: el SW vive en <base>sw.js. Es '/' en el launcher y en
// el teléfono, y '/wixplorer/' en GitHub Pages.
const BASE = new URL('./', self.location).pathname;

self.addEventListener('install', () => self.skipWaiting());

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  // Never cache API calls or non-same-origin requests
  if (url.pathname.startsWith(BASE + 'api/')) return;
  if (url.origin !== self.location.origin) return;

  // Cache-first for hashed assets under /assets/ (safe to cache forever)
  if (url.pathname.startsWith(BASE + 'assets/')) {
    event.respondWith(
      caches.open(CACHE).then((cache) =>
        cache.match(request).then((cached) => {
          if (cached) return cached;
          return fetch(request).then((response) => {
            if (response.ok) cache.put(request, response.clone());
            return response;
          });
        })
      )
    );
    return;
  }

  // Network-first for index.html — always get the latest shell
  if (url.pathname === BASE || url.pathname === BASE + 'index.html') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const forCache = response.clone();
            event.waitUntil(
              caches.open(CACHE).then((cache) => cache.put(request, forCache))
                .then(pruneStaleAssets)
                .catch(() => {})
            );
          }
          return response;
        })
        .catch(() => caches.match(request))
    );
  }
});

/**
 * Deletes cached /assets/* files that are not part of the current build.
 * Vite gives every build new hashed names, so without this the cache would
 * keep every old build forever. The list comes from /asset-manifest.json
 * (generated by vite.config.ts), which also covers lazily loaded chunks.
 * If the manifest is missing or empty, nothing is deleted.
 */
async function pruneStaleAssets() {
  const res = await fetch(BASE + 'asset-manifest.json', { cache: 'no-store' });
  if (!res.ok) return;
  const current = new Set(await res.json());
  if (current.size === 0) return;
  const cache = await caches.open(CACHE);
  const keys = await cache.keys();
  await Promise.all(keys.map((req) => {
    const path = new URL(req.url).pathname;
    if (path.startsWith(BASE + 'assets/') && !current.has(path)) return cache.delete(req);
    return undefined;
  }));
}
